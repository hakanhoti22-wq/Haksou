export const AUTO = { code: 'auto', name: 'Détecter la langue' };

const byCode = new Map(LANGUAGES.map(l => [l.code.toLowerCase(), l]));

/** Retrouve une langue à partir d'un code (moteur, ISO ou locale). */
export function findLanguage(code) {
  if (!code) return null;
  if (code === 'auto') return AUTO;
  const c = code.toLowerCase();
  if (byCode.has(c)) return byCode.get(c);
  const aliases = { he: 'iw', jv: 'jw', fil: 'tl', nb: 'no', 'zh': 'zh-cn', 'zh-hans': 'zh-cn', 'zh-hant': 'zh-tw', 'pt-br': 'pt', mni: 'mni-mtei' };
  if (aliases[c]) return byCode.get(aliases[c]);
  const base = c.split('-')[0];
  return byCode.get(aliases[base] || base) || null;
}

/** Code à envoyer au moteur de traduction. */
export const engineCode = lang => lang.engine || lang.code;

/** Locale vocale (ou code de repli). */
export const speechLocale = lang => lang.speech || lang.iso || lang.code;

const nativeCache = new Map();
/** Nom de la langue dans la langue elle-même (« Deutsch », « 日本語 »…). */
export function nativeName(lang) {
  if (nativeCache.has(lang.code)) return nativeCache.get(lang.code);
  let name = '';
  try {
    const iso = lang.iso || lang.code;
    const n = new Intl.DisplayNames([iso], { type: 'language' }).of(iso);
    if (n && n.toLowerCase() !== iso.toLowerCase()) name = n.charAt(0).toLocaleUpperCase(iso) + n.slice(1);
  } catch { /* langue inconnue du navigateur */ }
  nativeCache.set(lang.code, name);
  return name;
}
